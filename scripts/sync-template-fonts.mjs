#!/usr/bin/env node
// Copies the font files inject templates use into templates/_shared/fonts so rendering is
// deterministic, offline, and identical in packaged builds (ADR-0008). Re-run after
// upgrading @fontsource packages; the copied files are committed.
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const OUT = 'templates/_shared/fonts'
const FONTS = [
  ['inter', 'Inter', [400, 500, 600, 700]],
  ['roboto', 'Roboto', [400, 500, 700]],
  ['roboto-condensed', 'Roboto Condensed', [400, 700]],
  ['jetbrains-mono', 'JetBrains Mono', [400, 700]],
  ['source-serif-4', 'Source Serif 4', [400, 600, 700]],
  ['courier-prime', 'Courier Prime', [400, 700]],
  ['caveat', 'Caveat', [400, 700]],
]
mkdirSync(OUT, { recursive: true })
let css = '/* Generated by scripts/sync-template-fonts.mjs — do not edit. */\n'
for (const [pkg, family, weights] of FONTS) {
  for (const w of weights) {
    const file = `${pkg}-latin-${w}-normal.woff2`
    copyFileSync(join('node_modules/@fontsource', pkg, 'files', file), join(OUT, file))
    css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${w};font-display:block;src:url('fonts/${file}') format('woff2')}\n`
  }
}
writeFileSync('templates/_shared/fonts.css', css)
console.log('fonts synced')
