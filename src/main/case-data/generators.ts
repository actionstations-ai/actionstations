// Simulated case data (spec 0448 FR-10, NFR-5, ADR-0076). A generator turns parameters into
// consistent datasets with simple parametric code (no numerical models). The framework, not the
// generator, writes the provenance: origin is always `simulated`, the generator's id is
// recorded, and there is never a retrieval date, so simulated data cannot pass as historical.
import type { z } from 'zod'
import {
  CaseDataset,
  SeriesFile,
  TextFile,
  type CaseArea,
  type CaseDatasetKind,
  type CaseManifest,
  type CaseTimeRange,
} from '@shared/schemas/case-data'
import { AppError } from '../lib/errors'
import { addDatasets, roomLeft } from './store'

export interface GeneratedDataset {
  id: string
  label: string
  kind: Exclude<CaseDatasetKind, 'raster'>
  /** The data, in the file shape for its kind (series points, GeoJSON, text entries). */
  data: unknown
  range?: CaseTimeRange
  area?: CaseArea
  unit?: string
}

export interface SimulatedGenerator<P = unknown> {
  /** Lowercase id, e.g. "storm-track". */
  id: string
  label: string
  params: z.ZodType<P>
  /** Pure and deterministic: the same parameters give the same data. */
  generate(params: P): GeneratedDataset[]
}

const ID = /^[a-z0-9][a-z0-9-]{0,63}$/
const registry = new Map<string, SimulatedGenerator>()

export function registerGenerator<P>(g: SimulatedGenerator<P>): void {
  if (!ID.test(g.id)) throw new AppError('VALIDATION', `Invalid generator id: ${g.id}`)
  if (registry.has(g.id)) throw new AppError('CONFLICT', `Generator ${g.id} is already registered`)
  registry.set(g.id, g as SimulatedGenerator)
}

export const generatorIds = (): string[] => [...registry.keys()].sort()
export const listGenerators = (): { id: string; label: string }[] =>
  [...registry.values()]
    .map(({ id, label }) => ({ id, label }))
    .sort((a, b) => a.id.localeCompare(b.id))

/** Test hook. */
export const clearGenerators = (): void => registry.clear()

function validateData(d: GeneratedDataset): void {
  const schema = d.kind === 'series' ? SeriesFile : d.kind === 'features' ? null : TextFile
  const result = schema?.safeParse(d.data)
  if (result && !result.success)
    throw new AppError('VALIDATION', `Generated dataset ${d.id} is not valid ${d.kind} data`)
  if (d.kind === 'features' && (d.data as { type?: unknown } | null)?.type !== 'FeatureCollection')
    throw new AppError('VALIDATION', `Generated dataset ${d.id} is not a GeoJSON FeatureCollection`)
}

export interface GenerateDeps {
  maxMbPerScenario: number
}

export async function runGenerator(
  root: string,
  scenarioId: string,
  generatorId: string,
  rawParams: unknown,
  deps: GenerateDeps,
): Promise<CaseManifest> {
  const g = registry.get(generatorId)
  if (!g) throw new AppError('NOT_FOUND', `No generator named ${generatorId}`)
  const params = g.params.parse(rawParams)
  const generated = g.generate(params)
  const files = generated.map((d) => {
    validateData(d)
    return {
      name: `${d.id}.${d.kind === 'features' ? 'geojson' : 'json'}`,
      data: JSON.stringify(d.data),
    }
  })
  const total = files.reduce((n, f) => n + Buffer.byteLength(f.data), 0)
  const room = await roomLeft(root, scenarioId, deps.maxMbPerScenario)
  if (total > room)
    throw new AppError('VALIDATION', 'The simulated data does not fit the limit for this scenario')
  const datasets = generated.map((d, i) =>
    CaseDataset.parse({
      id: d.id,
      kind: d.kind,
      label: d.label,
      file: files[i]!.name,
      bytes: Buffer.byteLength(files[i]!.data),
      ...(d.range ? { range: d.range } : {}),
      ...(d.area ? { area: d.area } : {}),
      ...(d.unit ? { unit: d.unit } : {}),
      provenance: {
        origin: 'simulated',
        source: g.label,
        generator: g.id,
        terms: 'Generated by this app from the parameters you gave. Not a record of a real event.',
        citation: '',
      },
    }),
  )
  return addDatasets(root, scenarioId, datasets, files)
}
